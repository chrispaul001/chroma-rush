import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const gameDir = join(root, 'game');
const read = (name) => readFileSync(join(gameDir, name), 'utf8').trim();
const body = (name) => read(name).replace(/^import .*;\s*$/gm, '').replace(/^export\s+/gm, '');

const output = `/* Generated by scripts/build-offline.mjs. Keep game/src as the editable source. */
const Core = (() => {
${body('src/core.mjs')}
return { createGame, hashSeed, updateGame, rotate, setPaused, startGame, startRun, returnToMenu, restartGame, toggleMute, faceAtLane, difficultyAt, FACETS };
})();
const Renderer = (() => {
const { FACETS, faceAtLane, difficultyAt } = Core;
${body('src/render.mjs')}
return { createRenderer };
})();
const Controls = (() => {
const { rotate, setPaused, startGame, startRun, returnToMenu, restartGame, toggleMute } = Core;
${body('src/controls.mjs')}
return { attachControls };
})();
const { createGame, hashSeed, updateGame } = Core;
const { createRenderer } = Renderer;
const { attachControls } = Controls;
${read('main.mjs').replace(/^import .*;\s*$/gm, '')}
`;

writeFileSync(join(gameDir, 'offline.js'), output);
